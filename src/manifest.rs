use crate::manifest_parse::parse_markdown_content;
use crate::model::{
    ApiManifest, CliApi, CliArgItem, ConfigApi, HttpApi, ItemKind, LibraryApi, LibraryItem,
};
use std::fs;
use std::path::Path;

/// Manifest output format.
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Default,
    clap::ValueEnum,
    serde::Serialize,
    serde::Deserialize,
)]
#[serde(rename_all = "lowercase")]
pub enum ManifestFormat {
    /// GitHub Flavored Markdown (API.md)
    #[default]
    Markdown,
    /// Machine-readable structured JSON
    Json,
}

/// Manifest formatting and parsing errors.
#[derive(Debug, thiserror::Error)]
pub enum ManifestError {
    #[error("Failed to parse JSON manifest: {0}")]
    Json(#[from] serde_json::Error),

    #[error("Failed to read manifest file '{path}': {source}")]
    Io {
        path: std::path::PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("Failed to parse Markdown manifest: {0}")]
    ParseMarkdown(String),
}

/// Formats an `ApiManifest` as GitHub Flavored Markdown (`API.md`).
pub fn format_markdown(manifest: &ApiManifest) -> String {
    let mut out = String::new();
    let version_suffix = manifest
        .version
        .as_ref()
        .map(|v| format!(" (v{v})"))
        .unwrap_or_default();

    out.push_str(&format!(
        "# Public API Manifest: {}{}\n\n",
        manifest.name, version_suffix
    ));
    out.push_str("<!-- Generated by api-manifest. Do not edit manually. -->\n\n");

    let mut section_idx = 1;

    if let Some(ref lib) = manifest.library {
        format_library_markdown(&mut out, lib, section_idx);
        section_idx += 1;
    }

    if let Some(ref cli) = manifest.cli {
        format_cli_markdown(&mut out, cli, section_idx);
        section_idx += 1;
    }

    if let Some(ref http) = manifest.http {
        format_http_markdown(&mut out, http, section_idx);
        section_idx += 1;
    }

    if let Some(ref config) = manifest.config {
        format_config_markdown(&mut out, config, section_idx);
    }

    out
}

fn format_library_markdown(out: &mut String, lib: &LibraryApi, section_idx: usize) {
    out.push_str(&format!("## {section_idx}. Library API\n\n"));

    let mut functions = Vec::new();
    let mut methods = Vec::new();
    let mut structs = Vec::new();
    let mut enums = Vec::new();
    let mut traits = Vec::new();
    let mut type_aliases = Vec::new();
    let mut constants = Vec::new();
    let mut reexports = Vec::new();

    for item in &lib.items {
        match item.kind {
            ItemKind::Function => functions.push(item),
            ItemKind::Method => methods.push(item),
            ItemKind::Struct => structs.push(item),
            ItemKind::Field => {}
            ItemKind::Enum => enums.push(item),
            ItemKind::Trait => traits.push(item),
            ItemKind::TypeAlias => type_aliases.push(item),
            ItemKind::Constant | ItemKind::Static => constants.push(item),
            ItemKind::Reexport => reexports.push(item),
        }
    }

    format_section(out, "Structs", &structs);
    format_section(out, "Enums", &enums);
    format_section(out, "Functions", &functions);
    format_section(out, "Methods", &methods);
    format_section(out, "Traits", &traits);
    format_section(out, "Type Aliases", &type_aliases);
    format_section(out, "Constants & Statics", &constants);
    format_section(out, "Re-exports", &reexports);
}

fn format_section(out: &mut String, title: &str, items: &[&LibraryItem]) {
    if items.is_empty() {
        return;
    }
    out.push_str(&format!("### {title}\n\n"));
    for item in items {
        if let Some(ref doc) = item.doc {
            let first_line = doc.lines().next().unwrap_or_default();
            out.push_str(&format!("- `{}` — *{}*\n", item.signature, first_line));
        } else {
            out.push_str(&format!("- `{}`\n", item.signature));
        }
    }
    out.push('\n');
}

fn format_cli_markdown(out: &mut String, cli: &CliApi, section_idx: usize) {
    if cli.commands.is_empty() {
        return;
    }
    out.push_str(&format!("## {section_idx}. CLI API\n\n"));

    for cmd in &cli.commands {
        out.push_str(&format!("### `{}`\n\n", cmd.name));
        if let Some(ref about) = cmd.about {
            out.push_str(&format!("{about}\n\n"));
        }

        if !cmd.args.is_empty() {
            out.push_str("| Flag / Argument | Type | Required | Default | Description |\n");
            out.push_str("| --- | --- | --- | --- | --- |\n");
            for arg in &cmd.args {
                let flag_col = format_flag_col(arg);
                let type_col = arg.value_name.as_deref().unwrap_or("-");
                let req_col = if arg.required { "Yes" } else { "No" };
                let def_col = arg.default_value.as_deref().unwrap_or("-");
                let desc_col = arg.help.as_deref().unwrap_or("-");

                out.push_str(&format!(
                    "| {flag_col} | `{type_col}` | {req_col} | `{def_col}` | {desc_col} |\n"
                ));
            }
            out.push('\n');
        }

        if !cmd.subcommands.is_empty() {
            out.push_str("**Subcommands:**\n");
            for sub in &cmd.subcommands {
                out.push_str(&format!("- `{sub}`\n"));
            }
            out.push('\n');
        }
    }
}

fn format_flag_col(arg: &CliArgItem) -> String {
    let mut parts = Vec::new();
    if let Some(s) = arg.short {
        parts.push(format!("`-{s}`"));
    }
    if let Some(ref l) = arg.long {
        parts.push(format!("`--{l}`"));
    }
    if parts.is_empty() {
        format!("`<{}>`", arg.id.to_uppercase())
    } else {
        parts.join(", ")
    }
}

fn format_http_markdown(out: &mut String, http: &HttpApi, section_idx: usize) {
    if http.endpoints.is_empty() {
        return;
    }
    out.push_str(&format!("## {section_idx}. HTTP Endpoints\n\n"));
    out.push_str("| Method | Path | Handler | Description |\n");
    out.push_str("| --- | --- | --- | --- |\n");

    for ep in &http.endpoints {
        let desc = ep.doc.as_deref().unwrap_or("-");
        out.push_str(&format!(
            "| `{}` | `{}` | `{}` | {} |\n",
            ep.method, ep.path, ep.handler, desc
        ));
    }
    out.push('\n');
}

fn format_config_markdown(out: &mut String, config: &ConfigApi, section_idx: usize) {
    if config.sections.is_empty() {
        return;
    }
    out.push_str(&format!("## {section_idx}. Configuration Formats\n\n"));

    for sec in &config.sections {
        out.push_str(&format!(
            "### `{}` (*{}*)\n\n",
            sec.section, sec.file_format
        ));
        if let Some(ref desc) = sec.doc {
            out.push_str(&format!("{desc}\n\n"));
        }

        if !sec.options.is_empty() {
            out.push_str("| Key | Value Type | Default | Description |\n");
            out.push_str("| --- | --- | --- | --- | --- |\n");
            for opt in &sec.options {
                let def_col = opt.default_value.as_deref().unwrap_or("-");
                let desc_col = opt.doc.as_deref().unwrap_or("-");
                let safe_val_type = opt.value_type.replace('|', "\\|");
                out.push_str(&format!(
                    "| `{}` | `{safe_val_type}` | `{def_col}` | {desc_col} |\n",
                    opt.key
                ));
            }
            out.push('\n');
        }
    }
}

/// Parses an `ApiManifest` from file contents (supports JSON or Markdown).
pub fn parse_str(content: &str) -> Result<ApiManifest, ManifestError> {
    let trimmed = content.trim();

    if trimmed.starts_with('{') {
        return serde_json::from_str(trimmed).map_err(ManifestError::Json);
    }

    Ok(parse_markdown_content(content))
}

/// Reads and parses an `ApiManifest` from disk.
pub fn read_from_file(path: &Path) -> Result<ApiManifest, ManifestError> {
    let content = fs::read_to_string(path).map_err(|err| ManifestError::Io {
        path: path.to_path_buf(),
        source: err,
    })?;
    parse_str(&content)
}

#[cfg(test)]
mod tests {
    use super::*;
    use googletest::prelude::*;

    #[googletest::test]
    fn format_and_parse_roundtrip_preserves_manifest() -> Result<(), Box<dyn std::error::Error>> {
        let mut manifest = ApiManifest::new("demo-crate", Some("1.0.0".to_string()));
        let lib_item = LibraryItem::new(
            ItemKind::Function,
            "add",
            "demo_crate::add",
            "pub fn add(a: i32, b: i32) -> i32",
            Some("Add two numbers".to_string()),
        );
        manifest = manifest.with_library(LibraryApi::new(vec![lib_item]));

        let md = format_markdown(&manifest);
        expect_that!(
            md,
            contains_substring("# Public API Manifest: demo-crate (v1.0.0)")
        );
        expect_that!(md, contains_substring("pub fn add(a: i32, b: i32) -> i32"));

        let parsed = parse_str(&md)?;
        expect_that!(parsed.name, eq("demo-crate"));
        expect_that!(parsed.version, eq(&Some("1.0.0".to_string())));

        let lib = parsed.library.ok_or("Library API missing")?;
        expect_that!(lib.items.len(), eq(1));
        let item = lib.items.first().ok_or("Item missing")?;
        expect_that!(item.name, eq("add"));
        expect_that!(item.signature, eq("pub fn add(a: i32, b: i32) -> i32"));

        Ok(())
    }

    #[googletest::test]
    fn parse_json_manifest_succeeds() -> Result<(), Box<dyn std::error::Error>> {
        let manifest = ApiManifest::new("my-tool", Some("0.2.0".to_string()));
        let json = serde_json::to_string_pretty(&manifest)?;
        let parsed = parse_str(&json)?;
        expect_that!(parsed.name, eq("my-tool"));
        expect_that!(parsed.version, eq(&Some("0.2.0".to_string())));
        Ok(())
    }

    #[googletest::test]
    fn format_and_parse_member_functions_preserves_struct_name()
    -> Result<(), Box<dyn std::error::Error>> {
        let mut manifest = ApiManifest::new("demo-crate", Some("1.0.0".to_string()));
        let method_item = LibraryItem::new(
            ItemKind::Method,
            "Greeter::new",
            "demo_crate::Greeter::new",
            "pub fn Greeter::new(msg: String) -> Self",
            Some("Constructs a greeter".to_string()),
        );
        manifest = manifest.with_library(LibraryApi::new(vec![method_item]));

        let md = format_markdown(&manifest);
        expect_that!(md, contains_substring("### Methods"));
        expect_that!(
            md,
            contains_substring("pub fn Greeter::new(msg: String) -> Self")
        );

        let parsed = parse_str(&md)?;
        let lib = parsed.library.ok_or("Library API missing")?;
        expect_that!(lib.items.len(), eq(1));
        let item = lib.items.first().ok_or("Item missing")?;
        expect_that!(item.name, eq("Greeter::new"));
        expect_that!(item.kind, eq(ItemKind::Method));
        expect_that!(
            item.signature,
            eq("pub fn Greeter::new(msg: String) -> Self")
        );

        Ok(())
    }
}
