use crate::model::{
    ApiManifest, CliApi, CliArgItem, ConfigApi, HttpApi, ItemKind, LibraryApi, LibraryItem,
};
use std::fs;
use std::path::Path;

/// Manifest output format.
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Default,
    clap::ValueEnum,
    serde::Serialize,
    serde::Deserialize,
)]
#[serde(rename_all = "lowercase")]
pub(crate) enum ManifestFormat {
    /// GitHub Flavored Markdown (API.md)
    #[default]
    Markdown,
    /// Machine-readable structured JSON
    Json,
}

/// Manifest formatting and parsing errors.
#[derive(Debug, thiserror::Error)]
pub enum ManifestError {
    #[error("Failed to parse JSON manifest: {0}")]
    Json(#[from] serde_json::Error),

    #[error("Failed to read manifest file '{path}': {source}")]
    Io {
        path: std::path::PathBuf,
        #[source]
        source: std::io::Error,
    },

    #[error("Failed to parse Markdown manifest: {0}")]
    ParseMarkdown(String),
}

impl ApiManifest {
    pub(crate) fn format_markdown_inner(&self) -> String {
        let mut out = String::new();
        let version_suffix = self
            .version
            .as_ref()
            .map(|v| format!(" (v{v})"))
            .unwrap_or_default();

        out.push_str(&format!(
            "# Public API Manifest: {}{}\n\n",
            self.name, version_suffix
        ));
        out.push_str("<!-- Generated by api-manifest. Do not edit manually. -->\n\n");

        let mut section_idx = 1;

        if let Some(ref lib) = self.library {
            lib.format_markdown(&mut out, section_idx);
            section_idx += 1;
        }

        if let Some(ref cli) = self.cli {
            cli.format_markdown(&mut out, section_idx);
            section_idx += 1;
        }

        if let Some(ref http) = self.http {
            http.format_markdown(&mut out, section_idx);
            section_idx += 1;
        }

        if let Some(ref config) = self.config {
            config.format_markdown(&mut out, section_idx);
        }

        let trimmed = out.trim_end();
        format!("{trimmed}\n")
    }

    pub(crate) fn parse_str(content: &str) -> Result<Self, ManifestError> {
        let trimmed = content.trim();

        if trimmed.starts_with('{') {
            return serde_json::from_str(trimmed).map_err(ManifestError::Json);
        }

        Ok(Self::parse_markdown(content))
    }

    pub(crate) fn read_from_file_inner(path: &Path) -> Result<Self, ManifestError> {
        let content = fs::read_to_string(path).map_err(|err| ManifestError::Io {
            path: path.to_path_buf(),
            source: err,
        })?;
        Self::parse_str(&content)
    }
}

impl LibraryApi {
    fn format_markdown(&self, out: &mut String, section_idx: usize) {
        out.push_str(&format!("## {section_idx}. Library API\n\n"));

        let mut functions = Vec::new();
        let mut methods = Vec::new();
        let mut structs = Vec::new();
        let mut enums = Vec::new();
        let mut traits = Vec::new();
        let mut type_aliases = Vec::new();
        let mut constants = Vec::new();
        let mut reexports = Vec::new();

        for item in &self.items {
            match item.kind {
                ItemKind::Function => functions.push(item),
                ItemKind::Method => methods.push(item),
                ItemKind::Struct => structs.push(item),
                ItemKind::Field => {}
                ItemKind::Enum => enums.push(item),
                ItemKind::Trait => traits.push(item),
                ItemKind::TypeAlias => type_aliases.push(item),
                ItemKind::Constant | ItemKind::Static => constants.push(item),
                ItemKind::Reexport => reexports.push(item),
            }
        }

        Self::format_section(out, "Structs", &structs);
        Self::format_section(out, "Enums", &enums);
        Self::format_section(out, "Functions", &functions);
        Self::format_section(out, "Methods", &methods);
        Self::format_section(out, "Traits", &traits);
        Self::format_section(out, "Type Aliases", &type_aliases);
        Self::format_section(out, "Constants & Statics", &constants);
        Self::format_section(out, "Re-exports", &reexports);
    }

    fn format_section(out: &mut String, title: &str, items: &[&LibraryItem]) {
        if items.is_empty() {
            return;
        }
        out.push_str(&format!("### {title}\n\n"));
        for item in items {
            if let Some(ref doc) = item.doc {
                let first_line = doc.lines().next().unwrap_or_default();
                out.push_str(&format!("- `{}` — _{first_line}_\n", item.signature));
            } else {
                out.push_str(&format!("- `{}`\n", item.signature));
            }
        }
        out.push('\n');
    }
}

fn format_aligned_table(out: &mut String, headers: &[&str], rows: &[Vec<String>]) {
    let col_count = headers.len();
    let mut widths: Vec<usize> = headers.iter().map(|h| h.chars().count()).collect();

    for row in rows {
        for (i, cell) in row.iter().enumerate() {
            if let Some(w) = widths.get_mut(i) {
                let len = cell.chars().count();
                if len > *w {
                    *w = len;
                }
            }
        }
    }

    out.push('|');
    for (i, h) in headers.iter().enumerate() {
        let w = widths.get(i).copied().unwrap_or(3).max(3);
        out.push_str(&format!(" {h:<w$} |"));
    }
    out.push('\n');

    out.push('|');
    for i in 0..col_count {
        let w = widths.get(i).copied().unwrap_or(3).max(3);
        let dashes = "-".repeat(w);
        out.push_str(&format!(" {dashes} |"));
    }
    out.push('\n');

    for row in rows {
        out.push('|');
        for i in 0..col_count {
            let cell = row.get(i).map(String::as_str).unwrap_or_default();
            let w = widths.get(i).copied().unwrap_or(3).max(3);
            out.push_str(&format!(" {cell:<w$} |"));
        }
        out.push('\n');
    }
    out.push('\n');
}

impl CliApi {
    fn format_markdown(&self, out: &mut String, section_idx: usize) {
        if self.commands.is_empty() {
            return;
        }
        out.push_str(&format!("## {section_idx}. CLI API\n\n"));

        for cmd in &self.commands {
            out.push_str(&format!("### `{}`\n\n", cmd.name));
            if let Some(ref about) = cmd.about {
                out.push_str(&format!("{about}\n\n"));
            }

            if !cmd.args.is_empty() {
                let headers = [
                    "Flag / Argument",
                    "Type",
                    "Required",
                    "Default",
                    "Description",
                ];
                let rows: Vec<Vec<String>> = cmd
                    .args
                    .iter()
                    .map(|arg| {
                        let flag_col = arg.format_flag_col();
                        let type_col = format!("`{}`", arg.value_name.as_deref().unwrap_or("-"));
                        let req_col = if arg.required { "Yes" } else { "No" }.to_string();
                        let def_col = format!("`{}`", arg.default_value.as_deref().unwrap_or("-"));
                        let desc_col = arg.help.as_deref().unwrap_or("-").to_string();
                        vec![flag_col, type_col, req_col, def_col, desc_col]
                    })
                    .collect();
                format_aligned_table(out, &headers, &rows);
            }

            if !cmd.subcommands.is_empty() {
                out.push_str("**Subcommands:**\n\n");
                for sub in &cmd.subcommands {
                    out.push_str(&format!("- `{sub}`\n"));
                }
                out.push('\n');
            }
        }
    }
}

impl CliArgItem {
    fn format_flag_col(&self) -> String {
        let mut parts = Vec::new();
        if let Some(s) = self.short {
            parts.push(format!("`-{s}`"));
        }
        if let Some(ref l) = self.long {
            parts.push(format!("`--{l}`"));
        }
        if parts.is_empty() {
            format!("`<{}>`", self.id.to_uppercase())
        } else {
            parts.join(", ")
        }
    }
}

impl HttpApi {
    fn format_markdown(&self, out: &mut String, section_idx: usize) {
        if self.endpoints.is_empty() {
            return;
        }
        out.push_str(&format!("## {section_idx}. HTTP Endpoints\n\n"));
        let headers = ["Method", "Path", "Handler", "Description"];
        let rows: Vec<Vec<String>> = self
            .endpoints
            .iter()
            .map(|ep| {
                vec![
                    format!("`{}`", ep.method),
                    format!("`{}`", ep.path),
                    format!("`{}`", ep.handler),
                    ep.doc.as_deref().unwrap_or("-").to_string(),
                ]
            })
            .collect();
        format_aligned_table(out, &headers, &rows);
    }
}

impl ConfigApi {
    fn format_markdown(&self, out: &mut String, section_idx: usize) {
        if self.sections.is_empty() {
            return;
        }
        out.push_str(&format!("## {section_idx}. Configuration Formats\n\n"));

        for sec in &self.sections {
            out.push_str(&format!(
                "### `{}` (_{}_)\n\n",
                sec.section, sec.file_format
            ));
            if let Some(ref desc) = sec.doc {
                out.push_str(&format!("{desc}\n\n"));
            }

            if !sec.options.is_empty() {
                let headers = ["Key", "Value Type", "Default", "Description"];
                let rows: Vec<Vec<String>> = sec
                    .options
                    .iter()
                    .map(|opt| {
                        let def_col = opt.default_value.as_deref().unwrap_or("-");
                        let desc_col = opt.doc.as_deref().unwrap_or("-").to_string();
                        let safe_val_type = opt.value_type.replace('|', "\\|");
                        vec![
                            format!("`{}`", opt.key),
                            format!("`{safe_val_type}`"),
                            format!("`{def_col}`"),
                            desc_col,
                        ]
                    })
                    .collect();
                format_aligned_table(out, &headers, &rows);
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use googletest::prelude::*;

    #[googletest::test]
    fn format_and_parse_roundtrip_preserves_manifest() -> Result<(), Box<dyn std::error::Error>> {
        let mut manifest = ApiManifest::new("demo-crate", Some("1.0.0".to_string()));
        let lib_item = LibraryItem::new(
            ItemKind::Function,
            "add",
            "demo_crate::add",
            "pub fn add(a: i32, b: i32) -> i32",
            Some("Add two numbers".to_string()),
        );
        manifest = manifest.with_library(LibraryApi::new(vec![lib_item]));

        let md = manifest.format_markdown();
        expect_that!(
            md,
            contains_substring("# Public API Manifest: demo-crate (v1.0.0)")
        );
        expect_that!(md, contains_substring("pub fn add(a: i32, b: i32) -> i32"));

        let parsed = ApiManifest::parse_str(&md)?;
        expect_that!(parsed.name, eq("demo-crate"));
        expect_that!(parsed.version, eq(&Some("1.0.0".to_string())));

        let lib = parsed.library.ok_or("Library API missing")?;
        expect_that!(lib.items.len(), eq(1));
        let item = lib.items.first().ok_or("Item missing")?;
        expect_that!(item.name, eq("add"));
        expect_that!(item.signature, eq("pub fn add(a: i32, b: i32) -> i32"));

        Ok(())
    }

    #[googletest::test]
    fn parse_json_manifest_succeeds() -> Result<(), Box<dyn std::error::Error>> {
        let manifest = ApiManifest::new("my-tool", Some("0.2.0".to_string()));
        let json = serde_json::to_string_pretty(&manifest)?;
        let parsed = ApiManifest::parse_str(&json)?;
        expect_that!(parsed.name, eq("my-tool"));
        expect_that!(parsed.version, eq(&Some("0.2.0".to_string())));
        Ok(())
    }

    #[googletest::test]
    fn format_and_parse_member_functions_preserves_struct_name()
    -> Result<(), Box<dyn std::error::Error>> {
        let mut manifest = ApiManifest::new("demo-crate", Some("1.0.0".to_string()));
        let method_item = LibraryItem::new(
            ItemKind::Method,
            "Greeter::new",
            "demo_crate::Greeter::new",
            "pub fn Greeter::new(msg: String) -> Self",
            Some("Constructs a greeter".to_string()),
        );
        manifest = manifest.with_library(LibraryApi::new(vec![method_item]));

        let md = manifest.format_markdown();
        expect_that!(md, contains_substring("### Methods"));
        expect_that!(
            md,
            contains_substring("pub fn Greeter::new(msg: String) -> Self")
        );

        let parsed = ApiManifest::parse_str(&md)?;
        let lib = parsed.library.ok_or("Library API missing")?;
        expect_that!(lib.items.len(), eq(1));
        let item = lib.items.first().ok_or("Item missing")?;
        expect_that!(item.name, eq("Greeter::new"));
        expect_that!(item.kind, eq(ItemKind::Method));
        expect_that!(
            item.signature,
            eq("pub fn Greeter::new(msg: String) -> Self")
        );

        Ok(())
    }
}
